def tex_escape(s):
    """Escape LaTeX specials, leaving strings that already contain math ($...$) or
    LaTeX commands untouched."""
    s = str(s)
    if "$" in s or "\\" in s:
        return s
    for a, b in [("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"),
                 ("<=", r"$\le$"), (">=", r"$\ge$")]:
        s = s.replace(a, b)
    return s


def fmt(x, sig=4):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    if isinstance(x, (int, np.integer)):
        return f"{x:d}"
    x = float(x)
    if x == 0:
        return "0"
    if abs(x) >= 1e5 or abs(x) < 1e-3:
        return f"{x:.{sig - 1}e}"
    d = max(0, sig - 1 - int(math.floor(math.log10(abs(x)))))
    return f"{x:.{d}f}"


def pm(m, s, sig=4):
    if m is None or (isinstance(m, float) and math.isnan(m)):
        return "--"
    return f"${fmt(m, sig)} \\pm {fmt(s, 2)}$"


def write(name, header, rows, caption, colspec=None, tex_rows=None, note=None, tex_header=None):
    """Write <name>.csv (all columns), <name>.json (list of records) and <name>.tex.
    tex_header defaults to header; it must match the column count of tex_rows."""
    OUT.mkdir(exist_ok=True)
    with open(OUT / f"{name}.csv", "w", newline="") as f:
        w = csv.writer(f); w.writerow(header); w.writerows(rows)
    recs = [dict(zip(header, [(x.item() if hasattr(x, "item") else x) for x in r])) for r in rows]
    (OUT / f"{name}.json").write_text(json.dumps({"table": name, "caption": caption, "columns": header,
                                                  "rows": recs}, indent=1, default=str))
    trs = tex_rows if tex_rows is not None else [[tex_escape(fmt(c) if isinstance(c, (float, int, np.floating)) else c)
                                                  for c in r] for r in rows]
    th = tex_header or header
    if trs and len(trs[0]) != len(th):
        raise ValueError(f"{name}: LaTeX header has {len(th)} columns but rows have {len(trs[0])}")
    colspec = colspec or ("l" + "c" * (len(th) - 1))
    head = " & ".join(tex_escape(h) for h in th) + r" \\"
    body = [" & ".join(map(str, r)) + r" \\" for r in trs]
    if len(trs) > 26:  # long table: break across pages
        lines = [f"% generated by src/make_tables_v2.py — do not edit numbers by hand",
                 r"{\scriptsize", rf"\begin{{longtable}}{{@{{}}{colspec}@{{}}}}",
                 rf"\caption{{{caption}}}\label{{tab:v2_{name}}} \\", r"\toprule", head, r"\midrule", r"\endfirsthead",
                 r"\toprule", head, r"\midrule", r"\endhead", r"\bottomrule", r"\endfoot"]
        lines += body + [r"\end{longtable}"]
        if note:
            lines.append(rf"\par\smallskip{{\footnotesize {note}}}")
        lines.append("}")
    else:
        wide = len(th) > 8 and "p{" not in colspec
        lines = [f"% generated by src/make_tables_v2.py — do not edit numbers by hand",
                 r"\begin{table}[H]", r"\centering", r"\scriptsize",
                 rf"\caption{{{caption}}}", rf"\label{{tab:v2_{name}}}"]
        if wide:
            lines.append(r"\resizebox{\textwidth}{!}{%")
        lines += [rf"\begin{{tabular}}{{@{{}}{colspec}@{{}}}}", r"\toprule", head, r"\midrule"] + body + \
                 [r"\bottomrule", r"\end{tabular}" + ("}" if wide else "")]
        if note:
            lines.append(rf"\par\smallskip\parbox{{0.95\textwidth}}{{\footnotesize {note}}}")
        lines.append(r"\end{table}")
    (OUT / f"{name}.tex").write_text("\n".join(lines) + "\n")


def read_csv(p):
    p = Path(p)
    return list(csv.DictReader(open(p))) if p.exists() else []


def num(r, k):
    v = r.get(k, "")
    try:
        return float(v)
    except (TypeError, ValueError):
        return float("nan")


